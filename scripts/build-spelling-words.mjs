// Builds js/spelling-words.js: the words the Session VI "Spelling" tasks
// accept ("Add more examples below"). A word is accepted in a row when it is
// spelled that way and the CMU Pronouncing Dictionary gives it the sound.
// Only common words are kept (SCOWL, sizes 10–50).
//
//   npm install --no-save cmu-pronouncing-dictionary@3 wordlist-english@1
//   node scripts/build-spelling-words.mjs
//
// The rows must match the `list` ids of the spelling steps in js/exercises-pp.js.

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dictionary } from 'cmu-pronouncing-dictionary';

const require = createRequire(import.meta.url);
const listDir = require.resolve('wordlist-english/package.json').replace(/package\.json$/, '');

export const ROWS = {
  'ow-o': { spell: /o(?![aweu])/, sound: /\bOW\d/ },
  'ow-oe': { spell: /o(?:th|[bcdfgklmnprstvz])e/, sound: /\bOW\d/ },
  'ow-ow': { spell: /ow/, sound: /\bOW\d/ },
  'aw-ou': { spell: /ou/, sound: /\bAW\d/ },
  'aw-ow': { spell: /ow/, sound: /\bAW\d/ },
  'dj-j': { spell: /j/, sound: /\bJH\b/ },
  'dj-g': { spell: /g[eiy]/, sound: /\bJH\b/ },
};

const vocab = new Set();
for (const size of [10, 20, 35, 40, 50]) {
  for (const variant of ['english', 'american']) {
    for (const w of JSON.parse(readFileSync(`${listDir}${variant}-words-${size}.json`, 'utf8'))) {
      if (/^[a-z]+$/.test(w)) vocab.add(w);
    }
  }
}

// Every pronunciation of a word ("bow" and "bow(2)").
const prons = new Map();
for (const [key, p] of Object.entries(dictionary)) {
  const w = key.replace(/\(\d+\)$/, '');
  if (vocab.has(w)) prons.set(w, [...(prons.get(w) || []), p]);
}

const out = {};
for (const [id, { spell, sound }] of Object.entries(ROWS)) {
  out[id] = [...prons]
    .filter(([w, ps]) => spell.test(w) && ps.some((p) => sound.test(p)))
    .map(([w]) => w)
    .sort()
    .join(' ');
}

const header = `// Generated by scripts/build-spelling-words.mjs: do not edit by hand.
// Words for the Session VI spelling tasks, by row (spelling + sound).
//
// Pronunciations: CMU Pronouncing Dictionary (BSD-style licence; npm
// cmu-pronouncing-dictionary, ISC). Word frequency: SCOWL, sizes 10–50:
//   Copyright 2000-2016 by Kevin Atkinson
//   Permission to use, copy, modify, distribute and sell these word lists, the
//   associated scripts, the output created from the scripts, and its
//   documentation for any purpose is hereby granted without fee, provided that
//   the above copyright notice appears in all copies and that both that
//   copyright notice and this permission notice appear in supporting
//   documentation. Kevin Atkinson makes no representations about the
//   suitability of this array for any purpose. It is provided "as is" without
//   express or implied warranty.
`;
const body = Object.entries(out)
  .map(([id, words]) => `  '${id}': '${words}',`)
  .join('\n');
writeFileSync(new URL('../js/spelling-words.js', import.meta.url), `${header}\nexport const SPELLING_WORDS = {\n${body}\n};\n`);
for (const [id, words] of Object.entries(out)) console.log(id, words.split(' ').length);
